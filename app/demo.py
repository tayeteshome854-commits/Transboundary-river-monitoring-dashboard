"""DEMONSTRATION DATA provider — isolated, labelled, off by default.

This module exists so the interface can be developed, demoed and tested without
Earth Engine credentials.  It is *not* a data source:

* it is only reachable when ``ALLOW_DEMO_MODE=true`` **and** Earth Engine is
  unavailable (see :func:`demo_active`),
* every payload it produces carries ``data_status = "demonstration"`` and a
  human readable warning,
* it never produces raster tiles, gauge readings or anything that could be
  mistaken for an observation,
* values are deterministic for a given (basin, indicator, window) so screenshots
  and tests are reproducible.

Set ``ALLOW_DEMO_MODE=false`` (the default) for any operational deployment.
"""

from __future__ import annotations

import hashlib
import math
import time
from typing import Any, Optional

from .config import settings
from .errors import DataStatus
from .indicators import Indicator, get_indicator

WARNING = (
    "DEMONSTRATION DATA — these values are generated by the application to exercise the "
    "interface. They are not satellite observations, not measurements, and must not be used "
    "for decisions."
)

#: Plausible synthetic ranges per indicator (dimensionless indices are centred,
#: physical variables use realistic Ethiopian ranges).
_RANGES = {
    "ndvi": (0.15, 0.72),
    "evi": (0.10, 0.55),
    "ndwi": (-0.35, 0.25),
    "mndwi": (-0.40, 0.20),
    "rainfall": (50.0, 900.0),
    "lst": (18.0, 38.0),
    "air_temp": (14.0, 32.0),
    "et": (10.0, 90.0),
    "soil_moisture": (0.10, 0.38),
}


def demo_active() -> bool:
    from .ee_client import ee_client

    return bool(settings.allow_demo_mode) and not ee_client.is_available()


def _unit_random(*parts: Any) -> float:
    """Deterministic pseudo-random number in [0, 1) for a key tuple."""

    digest = hashlib.sha256("|".join(str(part) for part in parts).encode()).digest()
    return int.from_bytes(digest[:8], "big") / float(1 << 64)


def _value(indicator: Indicator, *parts: Any) -> float:
    low, high = _RANGES.get(indicator.id, (0.0, 1.0))
    return round(low + (high - low) * _unit_random(indicator.id, *parts), 4)


def demo_basin_statistics(
    basin_id: str,
    indicator_ids: list[str],
    window: dict[str, str],
    area_km2: Optional[float],
    region_label: str = "basin",
) -> dict[str, Any]:
    indicator_payloads = {}
    for name in indicator_ids:
        indicator = get_indicator(name)
        value = _value(indicator, basin_id, window["start"], window["end"])
        indicator_payloads[name] = {
            "indicator": name,
            "label": indicator.label,
            "units": indicator.units,
            "value": value,
            "std_dev": round(abs(value) * 0.12 + 0.02, 4),
            "data_status": DataStatus.DEMONSTRATION.value,
            "observation_count": 0,
            "valid_pixel_count": None,
            "expected_pixel_count": None,
            "coverage_fraction": None,
            "window": window,
            "latest_observation": None,
            "observation_age_days": None,
            "processed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "source": {"dataset": "synthetic (demonstration mode)", "scale_m": indicator.scale_m, "region": region_label},
            "caveat": WARNING,
            "note": WARNING,
        }
    return {
        "data_status": DataStatus.DEMONSTRATION.value,
        "warning": WARNING,
        "indicators": indicator_payloads,
    }


def demo_time_series(
    basin_id: str,
    indicator_id: str,
    start_year: int,
    end_year: int,
    aggregation: str = "year",
) -> dict[str, Any]:
    indicator = get_indicator(indicator_id)
    points = []
    for year in range(start_year, end_year + 1):
        months = range(1, 13) if aggregation == "month" else [None]
        for month in months:
            seasonal = 0.5 + 0.5 * math.sin(((month or 7) - 4) / 12.0 * 2 * math.pi)
            base = _value(indicator, basin_id, "series")
            spread = (indicator.extra or {}).get("spread", 0.15)
            value = base * (0.85 + 0.3 * seasonal) + _unit_random(indicator.id, basin_id, year, month) * spread
            points.append(
                {
                    "period": f"{year}" if month is None else f"{year}-{month:02d}",
                    "year": year,
                    "month": month,
                    "value": round(value, 4),
                    "std_dev": None,
                    "observation_count": 0,
                    "valid_pixel_count": None,
                    "latest_observation": None,
                    "data_status": DataStatus.DEMONSTRATION.value,
                    "note": WARNING,
                }
            )
    return {
        "indicator": indicator.id,
        "label": indicator.label,
        "units": indicator.units,
        "aggregation": aggregation,
        "series": points,
        "data_status": DataStatus.DEMONSTRATION.value,
        "warning": WARNING,
        "source": {"dataset": "synthetic (demonstration mode)"},
        "interpolation": "not applicable — synthetic series",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


__all__ = ["WARNING", "demo_active", "demo_basin_statistics", "demo_time_series"]
